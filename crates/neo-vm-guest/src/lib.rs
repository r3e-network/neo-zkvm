// Guest execution
// ============================================================================

/// Execute Neo VM and return proof output
#[must_use]
pub fn execute(input: ProofInput) -> ProofOutput {
    let mut vm = NeoVM::new(input.gas_limit);
    if let Err(e) = vm.load_script(input.script) {
        return ProofOutput {
            state: 1,
            gas_consumed: vm.gas_consumed,
            result: Some(StackItem::Boolean(false)),
            error: Some(e.to_string()),
        };
    }

    // Push arguments with VM's configured stack depth limit
    for arg in input.arguments {
        if vm.eval_stack.len() >= vm.max_stack_depth {
            return ProofOutput {
                state: 1,
                gas_consumed: vm.gas_consumed,
                result: Some(StackItem::Boolean(false)),
                error: Some(format!(
                    "Stack overflow: depth {} exceeds limit {}",
                    vm.eval_stack.len(),
                    vm.max_stack_depth
                )),
            };
        }
        vm.eval_stack.push(arg);
    }

    // Execute until halt or fault
    let mut runtime_error: Option<String> = None;
    while !matches!(vm.state, VMState::Halt | VMState::Fault) {
        if let Err(err) = vm.execute_next() {
            runtime_error = Some(err.to_string());
            vm.state = VMState::Fault;
            break;
        }
    }

    let state = match vm.state {
        VMState::Halt => 0,
        VMState::Fault => 1,
        _ => 2,
    };

    ProofOutput {
        state,
        result: vm.eval_stack.pop(),
        gas_consumed: vm.gas_consumed,
        error: if state == 1 {
            runtime_error.or_else(|| Some("Execution fault".to_string()))
        } else {
            None
        },
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde::Serialize;

    #[test]
    fn test_output_matches_public_inputs_roundtrip() {
        let output = ProofOutput {
            state: 0,
            result: Some(StackItem::Integer(5)),
            gas_consumed: 42,
            error: None,
        };
        let proof = NeoProof {
            output: output.clone(),
            proof_bytes: vec![],
            public_inputs: PublicInputs {
                script_hash: hash_data(b"script"),
                input_hash: hash_data(b"input"),
                output_hash: hash_proof_output(&output),
                gas_consumed: output.gas_consumed,
                execution_success: true,
            },
            vkey_hash: [0u8; 32],
            proof_mode: ProofMode::Mock,
            proof_format_version: PROOF_FORMAT_VERSION,
        };

        assert!(output_matches_public_inputs(&proof));
    }

    #[test]
    fn test_output_mismatch_detected() {
        let output = ProofOutput {
            state: 0,
            result: Some(StackItem::Integer(5)),
            gas_consumed: 42,
            error: None,
        };
        let mut proof = NeoProof {
            output: output.clone(),
            proof_bytes: vec![],
            public_inputs: PublicInputs {
                script_hash: hash_data(b"script"),
                input_hash: hash_data(b"input"),
                output_hash: hash_proof_output(&output),
                gas_consumed: output.gas_consumed,
                execution_success: true,
            },
            vkey_hash: [0u8; 32],
            proof_mode: ProofMode::Mock,
            proof_format_version: PROOF_FORMAT_VERSION,
        };
        proof.output.gas_consumed = proof.output.gas_consumed.saturating_add(1);

        assert!(!output_matches_public_inputs(&proof));
    }

    #[test]
    fn test_compute_commitment_changes_when_inputs_change() {
        let inputs_a = PublicInputs {
            script_hash: [1u8; 32],
            input_hash: [2u8; 32],
            output_hash: [3u8; 32],
            gas_consumed: 10,
            execution_success: true,
        };
        let mut inputs_b = inputs_a.clone();
        inputs_b.gas_consumed = 11;

        assert_ne!(compute_commitment(&inputs_a), compute_commitment(&inputs_b));
    }

    #[test]
    fn test_execute_reports_stack_overflow_for_excessive_arguments() {
        let input = ProofInput {
            script: vec![0x40], // RET
            arguments: vec![StackItem::Integer(1); 10_000],
            gas_limit: 1_000_000,
        };

        let output = execute(input);
        assert_eq!(output.state, 1);
        assert!(output
            .error
            .as_deref()
            .unwrap_or_default()
            .contains("Stack overflow"));
    }

    #[test]
    fn test_execute_reports_runtime_fault_error() {
        let input = ProofInput {
            script: vec![0xFF], // Invalid opcode
            arguments: vec![],
            gas_limit: 1_000_000,
        };

        let output = execute(input);
        assert_eq!(output.state, 1);
        assert!(output
            .error
            .as_deref()
            .unwrap_or_default()
            .contains("Invalid opcode"));
    }

    #[test]
    fn test_try_hash_proof_output_rejects_oversized_output() {
        let output = ProofOutput {
            state: 0,
            result: Some(StackItem::ByteString(vec![0u8; 10 * 1024 * 1024 + 1])),
            gas_consumed: 1,
            error: None,
        };
        assert!(try_hash_proof_output(&output).is_err());

        let proof = NeoProof {
            output,
            proof_bytes: vec![],
            public_inputs: PublicInputs {
                script_hash: [0u8; 32],
                input_hash: [0u8; 32],
                output_hash: [0u8; 32],
                gas_consumed: 1,
                execution_success: true,
            },
            vkey_hash: [0u8; 32],
            proof_mode: ProofMode::Mock,
            proof_format_version: PROOF_FORMAT_VERSION,
        };
        assert!(!output_matches_public_inputs(&proof));
    }

    #[test]
    fn test_legacy_neoproof_deserializes_with_default_format_version() {
        #[derive(Serialize)]
        struct LegacyNeoProof {
            output: ProofOutput,
            proof_bytes: Vec<u8>,
            public_inputs: PublicInputs,
            vkey_hash: [u8; 32],
            proof_mode: ProofMode,
        }

        let legacy = LegacyNeoProof {
            output: ProofOutput {
                state: 0,
                result: Some(StackItem::Integer(1)),
                gas_consumed: 1,
                error: None,
            },
            proof_bytes: vec![],
            public_inputs: PublicInputs {
                script_hash: [1u8; 32],
                input_hash: [2u8; 32],
                output_hash: [3u8; 32],
                gas_consumed: 1,
                execution_success: true,
            },
            vkey_hash: [0u8; 32],
            proof_mode: ProofMode::Mock,
        };

        let bytes = bincode_options()
            .serialize(&legacy)
            .expect("legacy serialize");
        let decoded = deserialize_neoproof(&bytes).expect("legacy deserialize should succeed");

        assert_eq!(decoded.proof_format_version, PROOF_FORMAT_VERSION);
    }
}
